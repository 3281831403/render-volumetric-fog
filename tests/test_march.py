"""Fixed acceptance tests for the volumetric fog exercise.

The tests intentionally exercise only the public stubs in ``fog.march``.
They are the specification; do not edit this file.
"""

from __future__ import annotations

import math

import pytest

from fog.march import (
    FogError,
    density,
    extinction,
    fog_batch,
    integrate,
    ray_box,
    sample_positions,
    step_count,
    validate_config,
)

TOL = 1e-6


def _camera(
    origin: tuple[float, float, float] = (0.0, 0.0, 0.0),
    direction: tuple[float, float, float] = (0.0, 0.0, 1.0),
    near: float = 1.0,
    far: float = 11.0,
) -> dict:
    return {"origin": origin, "dir": direction, "near": near, "far": far}


def _near_origin(camera: dict) -> tuple[float, float, float]:
    return tuple(
        camera["origin"][axis] + camera["dir"][axis] * camera["near"]
        for axis in range(3)
    )


def _config(**overrides) -> dict:
    config = {
        "density": 0.5,
        "height_falloff": 0.0,
        "noise_amplitude": 0.0,
        "noise_frequency": 1.0,
        "step": 0.1,
        "max_step": 1.0,
        "max_steps": 4096,
        "jitter": 0.5,
        "phase_g": 0.0,
        "mu": 0.0,
        "box": {"min": (-2.0, -1.0, 2.0), "max": (2.0, 1.0, 10.0)},
    }
    config.update(overrides)
    return config


def _uniform_samples(
    count: int = 10,
    step_len: float = 0.1,
    pos: tuple[float, float, float] = (0.0, 0.0, 5.0),
) -> list[dict]:
    return [{"pos": pos, "step_len": step_len} for _ in range(count)]


# 1. Defect: ray/box intersection is not clipped at the near plane.
def test_ray_box_clips_intersections_behind_the_near_plane() -> None:
    camera = _camera(near=2.0, far=12.0)
    near_origin = _near_origin(camera)

    behind = {"min": (-1.0, -1.0, -5.0), "max": (1.0, 1.0, 1.5)}
    assert ray_box(near_origin, camera["dir"], behind) == pytest.approx(
        (-1.0, -1.0), abs=TOL
    )

    crossing = {"min": (-1.0, -1.0, 0.0), "max": (1.0, 1.0, 8.0)}
    enter, leave = ray_box(near_origin, camera["dir"], crossing)
    assert enter == pytest.approx(0.0, abs=TOL)
    assert leave == pytest.approx(6.0, abs=TOL)


# 2. Defect: step count floors and drops the partial tail.
def test_step_count_rounds_up_and_keeps_the_final_segment() -> None:
    assert step_count(0.0, 1.0, 0.3) == 4
    assert step_count(0.0, 0.3, 0.1) == 3
    assert step_count(2.0, 2.0, 0.5) == 1


# 3. Defect: jitter exceeds one step and produces banding.
def test_sample_positions_keeps_jitter_inside_each_step() -> None:
    positions = sample_positions(1.0, 2.0, 4, 0.75)
    assert len(positions) == 4

    step_len = 0.25
    for index, position in enumerate(positions):
        start = 1.0 + index * step_len
        assert start - TOL <= position <= start + step_len + TOL

    assert sample_positions(1.0, 2.0, 4, 0.75) == positions


# 4. Defect: negative density is not clamped, so transmittance exceeds one.
def test_density_is_clamped_to_non_negative() -> None:
    config = _config(
        density=0.1,
        height_falloff=1.0,
        noise_amplitude=1.0,
        noise_frequency=1.0,
    )
    position = (0.0, 0.75 * math.pi, 0.0)

    result = density(position, config)
    assert result >= 0.0
    assert result == pytest.approx(0.0, abs=TOL)


# 5. Defect: extinction ignores step length, so results do not scale.
def test_extinction_scales_with_step_length() -> None:
    assert extinction(0.5, 2.0) == pytest.approx(1.0, abs=TOL)
    assert extinction(0.5, 4.0) == pytest.approx(2.0, abs=TOL)


# 6. Defect: integration uses a plain sum without transmittance decay.
def test_integrate_applies_transmittance_decay_per_step() -> None:
    result = integrate(
        _uniform_samples(count=10, step_len=0.1),
        _config(density=2.0, phase_g=0.0, mu=0.0),
    )
    expected_transmittance = math.exp(-2.0)

    assert result["transmittance"] == pytest.approx(
        expected_transmittance, abs=TOL
    )
    assert result["inscatter"] == pytest.approx(
        1.0 - expected_transmittance, abs=TOL
    )
    assert result["inscatter"] <= 1.0 - result["transmittance"] + TOL


# 7. Defect: in-scattering omits the phase function and is isotropic.
def test_inscatter_uses_the_phase_function() -> None:
    samples = _uniform_samples(count=10, step_len=0.1)
    isotropic = integrate(
        samples,
        _config(density=2.0, phase_g=0.0, mu=-1.0),
    )
    forward = integrate(
        samples,
        _config(density=2.0, phase_g=0.7, mu=-1.0),
    )

    transmittance = isotropic["transmittance"]
    assert forward["transmittance"] == pytest.approx(transmittance, abs=TOL)
    assert isotropic["inscatter"] == pytest.approx(1.0 - transmittance, abs=TOL)
    assert forward["inscatter"] < isotropic["inscatter"] - 1e-3
    assert 0.0 <= forward["inscatter"] <= 1.0 - transmittance + TOL


# 8. Defect: an excessively large step is not reported as banding risk.
def test_validate_config_flags_large_steps() -> None:
    issues = validate_config(_config(step=0.75, max_step=0.25), 4)
    assert "step is too large" in issues

    too_many = validate_config(_config(max_steps=2), 3)
    assert "too many steps" in too_many


# 9. Defect: fog_batch shares accumulators and leaks between rays.
def test_fog_batch_uses_independent_accumulators_per_ray() -> None:
    short_ray = _camera(far=4.0)
    long_ray = _camera(far=10.0)
    config = _config()

    combined = fog_batch([short_ray, long_ray], config)
    short_only = fog_batch([short_ray], config)
    long_only = fog_batch([long_ray], config)

    assert combined["transmittance"] == pytest.approx(
        [short_only["transmittance"][0], long_only["transmittance"][0]],
        abs=TOL,
    )
    assert combined["inscatter"] == pytest.approx(
        [short_only["inscatter"][0], long_only["inscatter"][0]],
        abs=TOL,
    )

    invalid_ray = _camera(near=5.0, far=4.0)
    with pytest.raises(FogError):
        fog_batch([short_ray, invalid_ray], config)


# 10. Defect: steps <= 0 is not validated, causing division by zero.
def test_validate_config_flags_non_positive_steps() -> None:
    issues = validate_config(_config(), 0)
    assert "steps must be positive" in issues


# Combination: zero density means no extinction and full transmittance.
def test_zero_density_gives_full_transmittance() -> None:
    result = integrate(
        _uniform_samples(count=8, step_len=0.25),
        _config(density=0.0, height_falloff=0.0, noise_amplitude=0.0),
    )
    assert result["transmittance"] == pytest.approx(1.0, abs=TOL)
    assert result["inscatter"] == pytest.approx(0.0, abs=TOL)


# Combination: uniform density follows the exponential attenuation law.
def test_uniform_density_matches_exponential_attenuation() -> None:
    result = integrate(
        _uniform_samples(count=8, step_len=0.5),
        _config(
            density=0.25,
            height_falloff=0.0,
            noise_amplitude=0.0,
            step=0.5,
        ),
    )
    assert result["transmittance"] == pytest.approx(math.exp(-1.0), abs=TOL)


# Combination: steps=0 must fail with FogError, never divide by zero.
def test_zero_steps_raises_fog_error() -> None:
    with pytest.raises(FogError):
        sample_positions(0.0, 1.0, 0, 0.5)


# Combination: a ray that misses the fog volume is fully transmissive.
def test_ray_miss_returns_full_transmittance() -> None:
    result = fog_batch(
        [_camera(direction=(0.0, 0.0, -1.0))],
        _config(),
    )
    assert result["transmittance"] == pytest.approx([1.0], abs=TOL)
    assert result["inscatter"] == pytest.approx([0.0], abs=TOL)


# Combination: successful batches preserve their input order.
def test_successful_batch_preserves_order() -> None:
    long_ray = _camera(far=11.0)
    short_ray = _camera(far=4.0)
    config = _config()

    ordered = fog_batch([long_ray, short_ray], config)
    swapped = fog_batch([short_ray, long_ray], config)

    assert ordered["transmittance"] == pytest.approx(
        list(reversed(swapped["transmittance"])), abs=TOL
    )
    assert ordered["inscatter"] == pytest.approx(
        list(reversed(swapped["inscatter"])), abs=TOL
    )
    assert ordered["transmittance"][0] < ordered["transmittance"][1] - 1e-3
    assert ordered["inscatter"][0] > ordered["inscatter"][1] + 1e-3
